#!/usr/bin/env python3
"""Measure the compile-time cost (wall-clock time and peak memory) of
several compilers, to catch compile-time blow-ups.

Targets:
- `layout`: test/abi/layout.c, with layout.h generated by genlayout.ml as in
  test/abi/Makefile (one very large function);
- `staticlayout`: test/abi/staticlayout.c, with the same layout.h;
- `spass`: all the source files of test/spass;
- `testc`: all the benchmarks of test/c.

Each file is compiled separately (`-c`), pinned to one core, under a memory
cap.  For a target made of several files, the time is the sum and the
memory is the maximum over its files.  A compilation that fails, runs out
of memory or exceeds the timeout is reported as null.

usage: compile_cost.py [--core C] [--mem-gb G] [--timeout T] [--targets t1,t2]
                       [--extra NAME=CMD ...] CONFIG...
Output: JSON {config: {target: {"time": seconds, "rss_mb": megabytes} or null}},
followed (on stderr) by a table.
"""
import argparse, json, os, resource, shutil, subprocess, sys, time

import suites
from bench import CONFIGS, PROGS

ROOT = suites.ROOT
TEST = os.path.join(ROOT, 'test')
TARGETS = ['layout', 'staticlayout', 'spass', 'testc']


def config_arch():
    """The ARCH variable of Makefile.config, as used by test/abi/Makefile."""
    for line in open(os.path.join(ROOT, 'Makefile.config')):
        if line.startswith('ARCH='):
            return line.split('=', 1)[1].strip()
    return None


def prepare_abi(out):
    """Copy the layout tests into `out`/abi and generate layout.h there."""
    abi = os.path.join(out, 'abi')
    os.makedirs(abi, exist_ok=True)
    shutil.copy(os.path.join(TEST, 'endian.h'), out)
    for f in ('layout.c', 'staticlayout.c', 'genlayout.ml'):
        shutil.copy(os.path.join(TEST, 'abi', f), abi)
    exe = os.path.join(abi, 'genlayout.exe')
    subprocess.run(['ocamlopt', '-g', '-o', exe, 'genlayout.ml'], cwd=abi, check=True,
                   capture_output=True)
    opts = ['-stable'] if config_arch() in ('arm', 'aarch64') else []
    with open(os.path.join(abi, 'layout.h'), 'w') as h:
        subprocess.run([exe] + opts, stdout=h, check=True)
    return abi


def spass_sources(d):
    """The SRCS of test/spass/Makefile (the directory also contains files
    generated by the test suite, such as *.light.c)."""
    text = open(os.path.join(d, 'Makefile')).read().replace('\\\n', ' ')
    for line in text.splitlines():
        if line.startswith('SRCS='):
            return line.split('=', 1)[1].split()
    raise RuntimeError('no SRCS in test/spass/Makefile')


def sources(target, abi):
    """The list of (source file, extra flags, working directory) of a target."""
    if target in ('layout', 'staticlayout'):
        return [(os.path.join(abi, target + '.c'), [], abi)]
    if target == 'spass':
        d = os.path.join(TEST, 'spass')
        return [(os.path.join(d, f), ['-fstruct-passing'], d) for f in spass_sources(d)]
    if target == 'testc':
        d = os.path.join(TEST, 'c')
        return [(os.path.join(d, p + '.c'), [], d) for p in PROGS]
    raise ValueError(target)


def compile_one(cmd, src, flags, cwd, obj, core, mem_gb, timeout):
    """Compile one file; return (seconds, peak RSS in MB), or None on failure."""
    limit = int(mem_gb * 2**30)

    def cap():
        resource.setrlimit(resource.RLIMIT_AS, (limit, limit))

    argv = ['taskset', '-c', str(core)] + cmd + flags + ['-w', '-c', '-o', obj, src]
    t = time.perf_counter()
    p = subprocess.Popen(argv, cwd=cwd, preexec_fn=cap,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    deadline = t + timeout
    while True:
        pid, status, ru = os.wait4(p.pid, os.WNOHANG)
        if pid:
            break
        if time.perf_counter() > deadline:
            p.kill()
            os.wait4(p.pid, 0)
            return None
        time.sleep(0.01)
    dt = time.perf_counter() - t
    p.returncode = os.waitstatus_to_exitcode(status)   # reaped by wait4 above
    if p.returncode:
        return None
    return dt, ru.ru_maxrss / 1024.0                   # ru_maxrss is in KB


def measure(cmd, target, abi, out, core, mem_gb, timeout):
    total, peak = 0.0, 0.0
    for src, flags, cwd in sources(target, abi):
        obj = os.path.join(out, 'out.o')
        r = compile_one(cmd, src, flags, cwd, obj, core, mem_gb, timeout)
        if r is None:
            print(f'  {target}: failed on {os.path.basename(src)}', file=sys.stderr)
            return None
        total, peak = total + r[0], max(peak, r[1])
    return {'time': round(total, 3), 'rss_mb': round(peak, 1)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('configs', nargs='+')
    ap.add_argument('--core', type=int, default=8, help='CPU core used for timing')
    ap.add_argument('--mem-gb', type=float, default=16, help='memory cap per compilation')
    ap.add_argument('--timeout', type=float, default=600, help='timeout per compilation (s)')
    ap.add_argument('--targets', default=','.join(TARGETS))
    ap.add_argument('--extra', action='append', default=[],
                    help='add a config, e.g. "mine=/path/ccomp -stdlib /path/runtime"')
    ap.add_argument('--out', default='/tmp/faster-compcert-cost', help='scratch directory')
    a = ap.parse_args()
    for e in a.extra:
        k, v = e.split('=', 1)
        CONFIGS[k] = v.split()
    os.makedirs(a.out, exist_ok=True)
    abi = prepare_abi(a.out)
    targets = a.targets.split(',')
    res = {}
    for c in a.configs:
        res[c] = {t: measure(CONFIGS[c], t, abi, a.out, a.core, a.mem_gb, a.timeout)
                  for t in targets}
    print(json.dumps(res, indent=1))
    print(f'{"target":14s}' + ''.join(f'{c:>24s}' for c in a.configs), file=sys.stderr)
    for t in targets:
        cells = []
        for c in a.configs:
            r = res[c][t]
            cells.append('failed' if r is None else f'{r["time"]:8.2f}s {r["rss_mb"]:8.0f}MB')
        print(f'{t:14s}' + ''.join(f'{x:>24s}' for x in cells), file=sys.stderr)


if __name__ == '__main__':
    main()
